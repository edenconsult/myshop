def preflight_legacy_data(apps, schema_editor):
    Order = apps.get_model("core", "Order")
    OrderItem = apps.get_model("core", "OrderItem")
    Product = apps.get_model("core", "Product")
    database = schema_editor.connection.alias
    issues = []

    invalid_products = []
    for product in Product.objects.using(database).order_by("pk").iterator():
        if (
            product.stock < 0
            or not product.cost.is_finite()
            or product.cost < 0
            or not product.price.is_finite()
            or product.price < 0
        ):
            invalid_products.append(str(product.pk))
    if invalid_products:
        issues.append(
            f"{len(invalid_products)} products have invalid stock/cost/price "
            f"(examples: {', '.join(invalid_products[:10])})"
        )

    invalid_items = []
    invalid_item_count = 0
    for item in OrderItem.objects.using(database).all().iterator():
        if (
            item.qty_bought <= 0
            or not item.paid_amount.is_finite()
            or item.paid_amount < 0
        ):
            invalid_item_count += 1
            if len(invalid_items) < 10:
                invalid_items.append(str(item.pk))
    if invalid_item_count:
        issues.append(
            f"{invalid_item_count} sale lines have non-positive quantity "
            f"(examples: {', '.join(map(str, invalid_items))})"
        )

    line_totals = dict(
        OrderItem.objects.using(database)
        .values("order_id")
        .annotate(total=Sum("paid_amount"))
        .values_list("order_id", "total")
    )
    invalid_orders = []
    for order in Order.objects.using(database).all().iterator():
        if (
            not order.overall_amount_paid.is_finite()
            or order.overall_amount_paid < 0
            or order.pk not in line_totals
            or line_totals.get(order.pk, Decimal("0.00"))
            != order.overall_amount_paid
        ):
            invalid_orders.append(str(order.pk))
    if invalid_orders:
        issues.append(
            f"{len(invalid_orders)} order totals do not reconcile "
            f"(examples: {', '.join(invalid_orders[:10])})"
        )

    if issues:
        raise RuntimeError(
            "Purchase-batch migration preflight failed; resolve these "
            "pre-existing issues before retrying: " + "; ".join(issues)
        )


def backfill_inventory(apps, schema_editor):
    OrderItem = apps.get_model("core", "OrderItem")
    Product = apps.get_model("core", "Product")
    StockBatch = apps.get_model("core", "StockBatch")
    StockReceipt = apps.get_model("core", "StockReceipt")
    database = schema_editor.connection.alias

    receipt = StockReceipt.objects.using(database).create(
        source="OPENING",
        received_at=timezone.now(),
        reason="Cutover opening stock; acquisition cost is estimated.",
        notes="Generated by the purchase-batch tracking migration.",
    )
    batches = []
    line_number = 0
    for product in Product.objects.using(database).all().iterator():
        if product.stock > 0:
            line_number += 1
            batches.append(
                StockBatch(
                    receipt=receipt,
                    product_id=product.pk,
                    line_number=line_number,
                    quantity_received=product.stock,
                    quantity_remaining=product.stock,
                    unit_cost=product.cost,
                    cost_is_estimated=True,
                )
            )
        if len(batches) >= 500:
            StockBatch.objects.using(database).bulk_create(batches, batch_size=500)
            batches.clear()
    if batches:
        StockBatch.objects.using(database).bulk_create(batches, batch_size=500)

    items = []
    for item in (
        OrderItem.objects.using(database)
        .select_related("product")
        .iterator()
    ):
        item.cost_amount = (
            item.product.cost * item.qty_bought
        ).quantize(Decimal("0.01"))
        item.cost_is_estimated = True
        items.append(item)
        if len(items) >= 500:
            OrderItem.objects.using(database).bulk_update(
                items,
                ["cost_amount", "cost_is_estimated"],
                batch_size=500,
            )
            items.clear()
    if items:
        OrderItem.objects.using(database).bulk_update(
            items,
            ["cost_amount", "cost_is_estimated"],
            batch_size=500,
        )


